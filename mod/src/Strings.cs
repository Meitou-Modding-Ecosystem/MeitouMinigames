    static readonly PzaStrings s_strings = new(Table);

    public static List<string> Init(string folder, string gameLanguage) => s_strings.Init(folder, gameLanguage, "auto", "lang/{code}.txt");
    public static string T(string key) => s_strings.T(key);
    public static string TF(string key, params object[] args) =>
        s_strings.TF(key, [.. args.Select(a => a is IFormattable f ? f.ToString(null, CultureInfo.InvariantCulture) : a?.ToString() ?? "")]);
    public static string Cats(long n) => n.ToString("N0", CultureInfo.InvariantCulture);
    public static string Name(Crawler c) => c is >= Crawler.WolfTail and <= Crawler.Plank ? T("crawler." + (int)c) : "";
}
